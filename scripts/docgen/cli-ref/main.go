// Command cli-ref emits docs/docs/reference/cli.md from the CLI command
// registry. Source of truth is the Go code: cli.Catalog() carries the name,
// summary, usage line, flags, subcommands, guard class, and terminal-app
// support of every subcommand, and mcp.ExcludedCLI carries the recorded
// reason a command has no MCP tool counterpart.
//
// Invoked by `make docs-regen` (writes the file) and `make docs-check`
// (writes to a tempfile, diffs against the checked-in copy, fails CI if they
// drift). The convention is: change the registry, regenerate, commit both in
// the same patch.
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/osauer/canary/v2/internal/cli"
	"github.com/osauer/canary/v2/internal/mcp"
)

const defaultOutput = "docs/docs/reference/cli.md"

