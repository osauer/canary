// Command broker-coverage emits the broker coverage page from the daemon's
// coverage table (internal/daemon/coverage.go): what each broker supplies,
// how each Canary capability runs on it, and why one is not served on OpenD.
// The same table decides what the daemon refuses under OpenD, so the page
// cannot drift from the behaviour.
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/osauer/canary/v2/internal/daemon"
)

const defaultOutput = "internal-docs/design/broker-coverage.md"

func main() {
	output := flag.String("o", defaultOutput, "output path (- for stdout)")
	flag.Parse()
	body := render()
	if *output == "-" {
		_, _ = os.Stdout.WriteString(body)
		return
	}
	if err := os.WriteFile(*output, []byte(body), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write:", err)
		os.Exit(1)
	}
}

var statusWords = map[daemon.CoverageStatus]string{
	daemon.Served:     "served",
	daemon.Partial:    "partial",
	daemon.Unverified: "unverified",
	daemon.Refused:    "refused",
	daemon.NotServed:  "not served",
}

var supplyWords = map[daemon.Supply]string{
	daemon.Supplied:    "supplied",
	daemon.Limited:     "limited",
	daemon.NotSupplied: "not supplied",
	daemon.ToVerify:    "to verify",
}

func render() string {
	caps := daemon.Capabilities()
	methods := daemon.CapabilityMethods()
	out := &strings.Builder{}
	out.WriteString("# Broker coverage\n\n")
	out.WriteString("*Generated by `scripts/docgen/broker-coverage` from `internal/daemon/coverage.go`. Do not edit by hand: change the table and run `make docs-regen`.*\n\n")
	out.WriteString("Canary reads one brokerage account through IBKR (TWS or IB Gateway) or through OpenD (moomoo, Futu). Most of what it shows is computed by Canary from what the broker supplies: the regime, portfolio stress, Edge and gamma are Canary's, not the broker's. So this page has two tables. The first says what each broker supplies. The second says how each capability runs on each broker and, where OpenD falls short, why. The same table decides what the daemon refuses under OpenD.\n\n")

	counts := map[daemon.CoverageStatus]int{}
	gaps := map[daemon.Gap]int{}
	for _, c := range caps {
		counts[c.OpenD.Status]++
		if g, _ := c.OpenDGap(); g != daemon.NoGap {
			gaps[g]++
		}
	}
	fmt.Fprintf(out, "On OpenD, of %d capabilities: %d served, %d partial, %d unverified, %d refused, %d not served. Of those not fully served, %d need data OpenD does not supply, %d wait on a check of what OpenD supplies, and %d have what they need from OpenD but are not yet read there.\n\n",
		len(caps), counts[daemon.Served], counts[daemon.Partial], counts[daemon.Unverified], counts[daemon.Refused], counts[daemon.NotServed],
		gaps[daemon.BrokerGap], gaps[daemon.UnknownGap], gaps[daemon.CanaryGap])

	out.WriteString("## What each broker supplies\n\n")
	out.WriteString("| Input | IBKR | OpenD | OpenD note |\n| --- | --- | --- | --- |\n")
	for _, in := range daemon.BrokerInputs() {
		fmt.Fprintf(out, "| %s | %s | %s | %s |\n", in.Name, supplyWords[in.IBKR], supplyWords[in.OpenD], cell(in.Note))
	}

	out.WriteString("\n## How each capability runs\n\n")
	out.WriteString("Statuses: *served* works and a test or live check shows it; *partial* works with the gap named; *unverified* answers, but nothing has confirmed it on that broker; *refused* is reached and answers that it cannot; *not served* is refused by the daemon before any handler runs. Why not on OpenD: *broker* means OpenD lacks a needed input, *to verify* means that is not yet known, *Canary* means OpenD supplies what it needs and Canary does not read it there yet.\n\n")
	out.WriteString("| Capability | Needs | IBKR | OpenD | Why not on OpenD | OpenD note |\n| --- | --- | --- | --- | --- | --- |\n")
	for _, c := range caps {
		g, why := c.OpenDGap()
		gap := string(g)
		if len(why) > 0 {
			gap += ": " + strings.Join(why, ", ")
		}
		needs := strings.Join(c.Needs, ", ")
		if needs == "" {
			needs = "no broker data"
		}
		fmt.Fprintf(out, "| %s | %s | %s | %s | %s | %s |\n", c.Name, needs, statusWords[c.IBKR.Status], statusWords[c.OpenD.Status], cell(gap), cell(c.OpenD.Note))
	}

	out.WriteString("\n## Proof and methods\n\n")
	out.WriteString("Tests run without a live broker; the wire smoke reads a live IBKR gateway (`scripts/wire-smoke.sh`). A capability with no proof listed has none beyond the daemon's ordinary tests.\n\n")
	out.WriteString("| Capability | IBKR proof | OpenD proof | Methods |\n| --- | --- | --- | --- |\n")
	for _, c := range caps {
		ms := methods[c.Name]
		list := "none: the daemon does it on its own"
		if len(ms) > 0 {
			list = "`" + strings.Join(ms, "`, `") + "`"
		}
		fmt.Fprintf(out, "| %s | %s | %s | %s |\n", c.Name, cell(proof(c.IBKR)), cell(proof(c.OpenD)), list)
	}
	return out.String()
}

func proof(c daemon.Coverage) string {
	var parts []string
	for _, p := range c.Smoke {
		parts = append(parts, "live smoke `"+p+"`")
	}
	for _, t := range c.Tests {
		parts = append(parts, "`"+t+"`")
	}
	if c.Seen != "" {
		parts = append(parts, c.Seen)
	}
	return strings.Join(parts, "; ")
}

// cell keeps a value on one table row.
func cell(s string) string {
	if s == "" {
		return " "
	}
	return strings.ReplaceAll(s, "|", "/")
}
