#!/usr/bin/env bash
# futu-proto.sh check is green on the tree and red on every change a manifest
# update did not accompany, each tried in a scratch copy.

set -euo pipefail

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
checker="$repo_root/scripts/futu-proto.sh"
pb=pkg/futu/internal/pb
test_root="$(mktemp -d "${TMPDIR:-/tmp}/canary-futu-proto-test.XXXXXX")"
trap 'rm -rf "$test_root"' EXIT HUP INT TERM

fresh() {
	rm -rf "$test_root/copy"
	mkdir -p "$test_root/copy/pkg/futu/internal" "$test_root/copy/tools"
	cp -R "$repo_root/$pb" "$test_root/copy/$pb"
	cp "$repo_root/go.mod" "$test_root/copy/go.mod"
	cp "$repo_root/tools/go.mod" "$test_root/copy/tools/go.mod"
}

flip_byte() {
	# Replace the file's first byte with a different one, same length.
	local file=$1 first
	first=$(head -c 1 "$file")
	if [ "$first" = "#" ]; then first=";"; else first="#"; fi
	{ printf '%s' "$first"; tail -c +2 "$file"; } >"$file.flip"
	mv "$file.flip" "$file"
}

assert_red() {
	local what=$1 expect=$2
	if "$checker" check "$test_root/copy" >/dev/null 2>"$test_root/error"; then
		echo "futu-proto test: $what passed the check" >&2
		exit 1
	fi
	if ! grep -q "$expect" "$test_root/error"; then
		echo "futu-proto test: $what reported the wrong failure:" >&2
		cat "$test_root/error" >&2
		exit 1
	fi
}

fresh
"$checker" check "$test_root/copy" >/dev/null

fresh
flip_byte "$test_root/copy/$pb/proto/Common.proto"
assert_red 'a one-byte change in a vendored definition' 'Common.proto does not match its manifest line'

fresh
flip_byte "$test_root/copy/$pb/common/Common.pb.go"
assert_red 'a one-byte change in a generated file' 'Common.pb.go does not match its manifest line'

fresh
printf 'syntax = "proto2";\n' >"$test_root/copy/$pb/proto/Trd_UnlockTrade.proto"
assert_red 'a vendored unlock definition' 'Trd_UnlockTrade.proto is vendored'

fresh
printf 'syntax = "proto2";\n' >"$test_root/copy/$pb/proto/Extra.proto"
assert_red 'a definition the manifest does not list' 'differ from the manifest'

fresh
rm "$test_root/copy/$pb/common/Common.pb.go"
assert_red 'a generated file the manifest lists and the tree lost' 'differ from the manifest'

fresh
sed -i.bak 's/^protoc-gen-go .*/protoc-gen-go v0.0.1/; s/^protobuf-runtime .*/protobuf-runtime v0.0.1/' "$test_root/copy/$pb/MANIFEST"
assert_red 'a manifest runtime line the go.mod pins disagree with' 'pins google.golang.org/protobuf'

fresh
sed -i.bak 's/^protoc-gen-go .*/protoc-gen-go v0.0.1/' "$test_root/copy/$pb/MANIFEST"
assert_red 'a generated header that names another generator' 'was not generated by protoc-gen-go'

fresh
sed -i.bak 's/^protoc-header .*/protoc-header v0.0.1/' "$test_root/copy/$pb/MANIFEST"
assert_red 'a generated header that names another protoc' 'was not generated by protoc v0.0.1'

fresh
sed -i.bak '/^archive /d' "$test_root/copy/$pb/MANIFEST"
assert_red 'a manifest without an archive checksum' 'no protoc archive checksum'

fresh
sed -i.bak 's/^\([[:space:]]*google\.golang\.org\/protobuf\) v[^ ]*/\1 v0.0.1/' "$test_root/copy/tools/go.mod"
assert_red 'a tool pin that disagrees with the manifest' 'tools/go.mod pins google.golang.org/protobuf v0.0.1'

fresh
rm "$test_root/copy/$pb/MANIFEST"
assert_red 'a missing manifest' 'MANIFEST is missing'

echo 'futu-proto test: OK'
