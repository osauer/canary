func TestRenderIsSortedRoundedAndStable(t *testing.T) {
	asOf := time.Date(2026, time.November, 2, 0, 0, 0, 0, time.UTC)
	weights := map[string]float64{"Utilities": 2.114, "Energy": 3.776, "Financials": 12.4}
	a, err := render(asOf, weights)
	if err != nil {
		t.Fatal(err)
	}
	b, _ := render(asOf, weights)
	if !bytes.Equal(a, b) {
		t.Fatal("render not byte-stable")
	}
	src := string(a)
	if !strings.HasPrefix(src, "// Code generated by scripts/refresh-fund-sectors. DO NOT EDIT.\n") {
		t.Fatal("generated-code header missing")
	}
	if !strings.Contains(src, `AsOf:   "2026-11-02"`) {
		t.Fatalf("as-of missing:\n%s", src)
	}
	e, f, u := strings.Index(src, `"Energy":     3.78`), strings.Index(src, `"Financials": 12.40`), strings.Index(src, `"Utilities":  2.11`)
	if e < 0 || f < 0 || u < 0 || !(e < f && f < u) {
		t.Fatalf("weights not rounded and sorted:\n%s", src)
	}
}
