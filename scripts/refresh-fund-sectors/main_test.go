// workbook builds a minimal xlsx with the layout State Street publishes:
// banner rows with the holdings date, a header row, holdings, a blank row,
// then disclaimer text that must not be read as holdings.
func workbook(t *testing.T, asOfCell string) []byte {
	t.Helper()
	shared := `<?xml version="1.0" encoding="UTF-8"?>
<sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">` +
		`<si><t>Holdings:</t></si>` + // 0
		`<si><t>` + asOfCell + `</t></si>` + // 1
		`<si><t>Name</t></si><si><t>Ticker</t></si><si><t>Weight</t></si><si><t>Sector</t></si>` + // 2-5
		`<si><t>AAPL</t></si><si><t>BRK.B</t></si><si><t>-</t></si>` + // 6-8
		`<si><r><t>Rich </t></r><r><t>text</t></r></si>` + // 9
		`</sst>`
	sheet := `<?xml version="1.0" encoding="UTF-8"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>
<row r="3"><c r="A3" t="s"><v>0</v></c><c r="B3" t="s"><v>1</v></c></row>
<row r="5"><c r="A5" t="s"><v>2</v></c><c r="B5" t="s"><v>3</v></c><c r="E5" t="s"><v>4</v></c><c r="F5" t="s"><v>5</v></c></row>
<row r="6"><c r="B6" t="s"><v>6</v></c><c r="E6"><v>7.5</v></c><c r="F6" t="s"><v>8</v></c></row>
<row r="7"><c r="B7" t="s"><v>7</v></c><c r="E7"><v>1.25</v></c></row>
<row r="8"><c r="B8" t="inlineStr"><is><t>MSFT</t></is></c><c r="E8"><v>3.0E-6</v></c></row>
<row r="9"><c r="B9" t="s"><v>8</v></c><c r="E9"><v>0.08</v></c></row>
<row r="10"></row>
<row r="12"><c r="A12" t="s"><v>9</v></c></row>
</sheetData></worksheet>`
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for name, body := range map[string]string{"xl/sharedStrings.xml": shared, "xl/worksheets/sheet1.xml": sheet} {
		w, err := zw.Create(name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := w.Write([]byte(body)); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func TestParseWorkbookReadsHoldingsAndTheWorkbookDate(t *testing.T) {
	holdings, asOf, err := parseWorkbook(workbook(t, "As of 02-Nov-2026"))
	if err != nil {
		t.Fatal(err)
	}
	if want := time.Date(2026, time.November, 2, 0, 0, 0, 0, time.UTC); !asOf.Equal(want) {
		t.Fatalf("as-of %v, want the workbook's date %v", asOf, want)
	}
	want := []holding{{"AAPL", 7.5}, {"BRK.B", 1.25}, {"MSFT", 3e-6}, {"-", 0.08}}
	if len(holdings) != len(want) {
		t.Fatalf("holdings %+v, want %+v", holdings, want)
	}
	for i := range want {
		if holdings[i] != want[i] {
			t.Fatalf("holding %d = %+v, want %+v", i, holdings[i], want[i])
		}
	}
}

func TestParseWorkbookFailsWithoutAHoldingsDate(t *testing.T) {
	if _, _, err := parseWorkbook(workbook(t, "Holdings")); err == nil || !strings.Contains(err.Error(), "As of") {
		t.Fatalf("missing date accepted: %v", err)
	}
	if _, _, err := parseWorkbook([]byte("<html>bot wall</html>")); err == nil {
		t.Fatal("non-zip accepted")
	}
}

func TestAggregateSumsBySectorAndKeepsUnresolved(t *testing.T) {
	sectors := map[string]string{"AAPL": "Information Technology", "MSFT": "Information Technology", "BRK.B": "Financials"}
	s := aggregate([]holding{{"AAPL", 7.5}, {"BRK.B", 1.25}, {"MSFT", 0.5}, {"-", 0.08}}, func(t string) (string, bool) {
		v, ok := sectors[t]
		return v, ok
	})
	if s.Resolved != 3 || s.Sum != 9.25 || s.Weights["Information Technology"] != 8 || s.Weights["Financials"] != 1.25 {
		t.Fatalf("split %+v", s)
	}
	if len(s.Unresolved) != 1 || s.Unresolved[0].Ticker != "-" {
		t.Fatalf("unresolved %+v", s.Unresolved)
	}
}

